export interface SetupConfig {
  wanInterface: string;
  lanBridge: string;
  ssid: string;
  wanIp: string;
  gateway: string;
  radiusSecret: string;
  timeZone: string;
}

export const generateSetupScript = (config: Partial<SetupConfig>) => {
  const wanIface = (config.wanInterface || 'ether1').trim();
  const lanBridge = (config.lanBridge || 'bridge1').trim();
  const ssid = (config.ssid || 'Al-afia -Net').trim();
  let wanIp = (config.wanIp || '192.168.1.20/24').trim();
  if (!wanIp.includes('/')) {
    wanIp = `${wanIp}/24`;
  }
  const gateway = (config.gateway || '192.168.1.1').trim();
  const radiusSecret = (config.radiusSecret || '2026').trim();
  const timeZone = (config.timeZone || 'Asia/Riyadh').trim();

  return `
# ============================================================
# Clean RouterOS 7.x/6.x - Hotspot + User-Manager Setup
# Generated by ZCtrl Automated Router Setup
# ============================================================

# 1. Bridge Configuration
:do { /interface bridge add name="${lanBridge}" comment="ZCtrl LAN Bridge" } on-error={}

# 2. Wireless / WiFi Setup
:if ([:len [/interface/wifi find default-name=wifi1]] > 0) do={
    :do { /interface/wifi set [find default-name=wifi1] configuration.mode=ap .ssid="${ssid}" disabled=no } on-error={}
}
:if ([:len [/interface/wireless find default-name=wlan1]] > 0) do={
    :do { /interface/wireless set [find default-name=wlan1] mode=ap-bridge ssid="${ssid}" disabled=no } on-error={}
}

# 3. Management Interface List
:do { /interface list add comment="SEC|MGMT" name=MGMT-IFACES } on-error={}
:do { /interface list member add list=MGMT-IFACES interface="${lanBridge}" } on-error={}

# 4. Bridge Ports (Add all non-WAN ethernet ports & wireless interfaces)
:foreach i in=[/interface ethernet find] do={
    :local n [/interface ethernet get $i name]
    :if ($n != "${wanIface}") do={
        :do { /interface bridge port add bridge="${lanBridge}" interface=$n } on-error={}
    }
}
:if ([:len [/interface/wifi find]] > 0) do={
    :foreach w in=[/interface/wifi find] do={
        :do { /interface bridge port add bridge="${lanBridge}" interface=[/interface/wifi get $w name] } on-error={}
    }
}
:if ([:len [/interface/wireless find]] > 0) do={
    :foreach w in=[/interface/wireless find] do={
        :do { /interface bridge port add bridge="${lanBridge}" interface=[/interface/wireless get $w name] } on-error={}
    }
}

# 5. IP Addresses
:do { /ip address add address="${wanIp}" interface="${wanIface}" comment="ZCtrl WAN IP" } on-error={}
:do { /ip address add address=10.0.0.1/22 interface="${lanBridge}" comment="ZCtrl Hotspot Gateway" } on-error={}

# 6. Default Route (Gateway)
:do { /ip route add disabled=no dst-address=0.0.0.0/0 gateway="${gateway}" comment="ZCtrl Default Route" } on-error={}

# 7. DNS Settings
:do { /ip dns set allow-remote-requests=yes servers=1.1.1.1,8.8.8.8 } on-error={}

# 8. IP Pool & DHCP Server
:do { /ip pool add name=dhcp_pool0 ranges=10.0.0.2-10.0.3.254 } on-error={}
:do { /ip dhcp-server add address-pool=dhcp_pool0 interface="${lanBridge}" name=dhcp1 disabled=no } on-error={}
:do { /ip dhcp-server network add address=10.0.0.0/22 dns-server=10.0.0.1,8.8.8.8 gateway=10.0.0.1 comment="ZCtrl Hotspot Network" } on-error={}

# 9. Hotspot Server Profile & Server
:do {
  /ip hotspot profile add dns-name=alafia.net hotspot-address=10.0.0.1 html-directory=alafia.NET3 login-by=http-chap,http-pap name="HOTSPOT SERVER" radius-interim-update=5m use-radius=yes
} on-error={}
:do { /ip hotspot add address-pool=dhcp_pool0 addresses-per-mac=1 disabled=no interface="${lanBridge}" name=hotspot1 profile="HOTSPOT SERVER" } on-error={}

# 10. Management IP Access List (Prevents locking admin out!)
:do { /ip firewall address-list add address=10.0.0.0/8 comment="ZCtrl Hotspot Admin" list=MGMT-ALLOW } on-error={}
:do { /ip firewall address-list add address=192.168.0.0/16 comment="ZCtrl LAN Admin" list=MGMT-ALLOW } on-error={}
:do { /ip firewall address-list add address=172.16.0.0/12 comment="ZCtrl Private Net" list=MGMT-ALLOW } on-error={}

# 11. Firewall NAT & Mangle
:do { /ip firewall nat add action=masquerade chain=srcnat comment="MASQUERADE-INTERNET-MAIN" out-interface="${wanIface}" } on-error={}
:do { /ip firewall nat add action=redirect chain=dstnat comment="DNS Redirect UDP" dst-port=53 protocol=udp to-ports=53 } on-error={}
:do { /ip firewall nat add action=redirect chain=dstnat comment="DNS Redirect TCP" dst-port=53 protocol=tcp to-ports=53 } on-error={}
:do { /ip firewall mangle add action=change-mss chain=forward comment="Fix MTU/MSS Issues" new-mss=clamp-to-pmtu protocol=tcp tcp-flags=syn } on-error={}

# 12. Firewall Filter Rules (Safe Input & Forward Protection)
:do { /ip firewall filter add action=accept chain=input comment="SEC|Allow-ZCtrl-API" dst-port=8728,8729,8291 protocol=tcp src-address-list=MGMT-ALLOW } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="SEC|CoA-local-only" dst-port=3799 protocol=udp src-address=127.0.0.1 } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow established input" connection-state=established,related } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow ICMP" protocol=icmp } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow DHCP from hotspot" dst-port=67 in-interface="${lanBridge}" protocol=udp } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow DNS UDP from hotspot" dst-port=53 in-interface="${lanBridge}" protocol=udp } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow DNS TCP from hotspot" dst-port=53 in-interface="${lanBridge}" protocol=tcp } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow HTTP/HTTPS for hotspot" dst-port=80,443 in-interface="${lanBridge}" protocol=tcp } on-error={}
:do { /ip firewall filter add action=accept chain=input comment="Allow management from MGMT-ALLOW" src-address-list=MGMT-ALLOW } on-error={}
:do { /ip firewall filter add action=drop chain=input comment="Drop WAN input" in-interface="${wanIface}" } on-error={}
:do { /ip firewall filter add action=accept chain=forward comment="Allow established forward" connection-state=established,related } on-error={}
:do { /ip firewall filter add action=accept chain=forward comment="Allow LAN to WAN" in-interface="${lanBridge}" out-interface="${wanIface}" } on-error={}
:do { /ip firewall filter add action=drop chain=forward comment="Drop WAN forward" in-interface="${wanIface}" } on-error={}

# 13. Radius Client
:do { /ppp aaa set use-radius=yes } on-error={}
:do { /radius add address=127.0.0.1 secret="${radiusSecret}" service=hotspot timeout=3s comment="ZCtrl Local Radius" } on-error={}
:do { /radius incoming set accept=yes } on-error={}

# 14. System Clock & NTP
:do { /system clock set time-zone-name="${timeZone}" } on-error={}
:do { /system ntp client set enabled=yes } on-error={}
:do { /system ntp client servers add address=162.159.200.1 comment="Cloudflare NTP" } on-error={}
:do { /system ntp client servers add address=216.239.35.0 comment="Google NTP" } on-error={}

# 15. System Services & Security Hardening
:do { /ip service set ftp disabled=yes } on-error={}
:do { /ip service set telnet disabled=yes } on-error={}
:do { /tool bandwidth-server set enabled=no } on-error={}
:do { /tool mac-server mac-winbox set allowed-interface-list=MGMT-IFACES } on-error={}

# 16. User-Manager Setup (Profiles, Limitations & Router)
:do { /user-manager set enabled=yes use-profiles=yes } on-error={}
:do { /user-manager advanced set web-private-password="${radiusSecret}" web-private-username=admin } on-error={}
:do { /user-manager router add address=127.0.0.1 name=Local-Router shared-secret="${radiusSecret}" } on-error={}

:do { /user-manager limitation add name=Lim-1H-Strict uptime-limit=1h } on-error={}
:do { /user-manager limitation add name=Lim-1Week-Strict uptime-limit=1w } on-error={}
:do { /user-manager limitation add name=Lim-1Month-Strict uptime-limit=4w2d } on-error={}
:do { /user-manager limitation add comment="الادارة" name=unlimited } on-error={}
:do { /user-manager limitation add name=Lim-3H-Converted uptime-limit=3h } on-error={}

:do { /user-manager profile add name=Prof-1H-Valid24H name-for-users="1 Hour (Valid 24H)" override-shared-users=1 starts-when=first-auth validity=1d } on-error={}
:do { /user-manager profile add name=Prof-1Week-Unlimited name-for-users="1 Week Unlimited" override-shared-users=1 starts-when=first-auth validity=1w } on-error={}
:do { /user-manager profile add name=Prof-1Month-Unlimited name-for-users="1 Month Unlimited" override-shared-users=1 starts-when=first-auth validity=4w2d } on-error={}
:do { /user-manager profile add comment="الادارة" name=unlimited name-for-users=unlimited override-shared-users=1 starts-when=first-auth validity=unlimited } on-error={}
:do { /user-manager profile add name=Prof-3H-Converted name-for-users="3 Hours Converted" override-shared-users=1 starts-when=first-auth validity=2d } on-error={}

:do { /user-manager profile-limitation add limitation=Lim-1H-Strict profile=Prof-1H-Valid24H } on-error={}
:do { /user-manager profile-limitation add limitation=Lim-1Week-Strict profile=Prof-1Week-Unlimited } on-error={}
:do { /user-manager profile-limitation add limitation=Lim-1Month-Strict profile=Prof-1Month-Unlimited } on-error={}
:do { /user-manager profile-limitation add comment="الادارة" limitation=unlimited profile=unlimited } on-error={}
:do { /user-manager profile-limitation add limitation=Lim-3H-Converted profile=Prof-3H-Converted } on-error={}
`;
};
