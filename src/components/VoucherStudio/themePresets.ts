export function applyThemeToDesign(
  prevDesign: VoucherDesignState,
  themeName: VoucherDesignState['theme']
): VoucherDesignState {
  const preset = THEME_PRESETS[themeName] || THEME_PRESETS.modern;

  return {
    ...prevDesign,
    theme: themeName,
    bgColor: preset.bgColor,
    cardTextColor: preset.cardTextColor,
    borderColor: preset.borderColor,
    primaryColor: preset.primaryColor,
    fontFamily: preset.fontFamily,
    layoutStyle: preset.layoutStyle,
    elements: {
      network: {
        ...preset.elements.network,
        rotation: 0,
        show: prevDesign.elements?.network?.show !== false,
      },
      user: {
        ...preset.elements.user,
        rotation: 0,
        show: prevDesign.elements?.user?.show !== false,
      },
      password: {
        ...preset.elements.password,
        rotation: 0,
        show: prevDesign.elements?.password?.show !== false,
      },
      price: {
        ...preset.elements.price,
        rotation: 0,
        show: prevDesign.elements?.price?.show !== false,
      },
      time: {
        ...preset.elements.time,
        rotation: 0,
        show: prevDesign.elements?.time?.show !== false,
      },
      profile: {
        ...preset.elements.profile,
        rotation: 0,
        show: prevDesign.elements?.profile?.show !== false,
      },
      dataLimit: {
        ...preset.elements.dataLimit,
        rotation: 0,
        show: prevDesign.elements?.dataLimit?.show !== false,
      },
    },
    coords: JSON.parse(JSON.stringify(preset.coords)),
  };
}
